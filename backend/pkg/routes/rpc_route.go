	rpc.Method("lti_attempt.create", controllers.LTIAttemptCreate)
	rpc.Method("lti_attempt.update", controllers.LTIAttemptUpdate)
	rpc.Method("lti_attempt.list", controllers.LTIAttemptList)
	rpc.Method("lti_attempt.delete", controllers.LTIAttemptDelete)
	rpc.Method("lti_attempt.get", controllers.LTIAttemptGet)
	rpc.Method("lti_attempt.list_external", controllers.LTIAttemptListExternal)
	rpc.Method("lti_attempt.update_external", controllers.LTIAttemptUpdateExternal)
	rpc.Method("lab_catalog.list", controllers.LabCatalogList)
	rpc.Method("lab_catalog.start", controllers.LabCatalogStart)
	rpc.Method("auth_provider.upsert", controllers.AuthProviderUpsert)
	rpc.Method("auth_provider.list", controllers.AuthProviderList)
	rpc.Method("auth_provider.delete", controllers.AuthProviderDelete)
	rpc.Method("auth_provider.get", controllers.AuthProviderGet)
	rpc.Method("lti_routing.upsert", controllers.LTIRoutingUpsert)
	rpc.Method("lti_routing.list", controllers.LTIRoutingList)
	rpc.Method("lti_routing.delete", controllers.LTIRoutingDelete)
	rpc.Method("lti_routing.get", controllers.LTIRoutingGet)
	rpc.Method("server.upsert", controllers.ServerUpsert)
	rpc.Method("server.list", controllers.ServerList)
	rpc.Method("server.delete", controllers.ServerDelete)
	rpc.Method("server.get", controllers.ServerGet)
	rpc.Method("server_queue.upsert", controllers.ServerQueueUpsert)
	rpc.Method("server_queue.list", controllers.ServerQueueList)
	rpc.Method("role.upsert", controllers.RoleUpsert)
	rpc.Method("role.list", controllers.RoleList)
	rpc.Method("role.delete", controllers.RoleDelete)
	rpc.Method("service_card.upsert", controllers.ServiceCardUpsert)
	rpc.Method("service_card.list", controllers.ServiceCardList)
	rpc.Method("service_card.delete", controllers.ServiceCardDelete)
	rpc.Method("service_card.get", controllers.ServiceCardGet)
	rpc.Method("sso.authorize", controllers.SSOAuthorizePost)
	rpc.Method("user.global_store_get", controllers.UserGlobalStoreGet)
	rpc.Method("user.global_store_set", controllers.UserGlobalStoreSet)
	rpc.Method("user.token_refresh", controllers.UserTokenRefresh)
	rpc.Method("user.login", controllers.UserLogin)
	rpc.Method("user.logout", controllers.UserLogout)
	rpc.Method("user.password_change", controllers.UserPasswordChange)
	rpc.Method("user.upsert", controllers.UserUpsert)
	rpc.Method("user.list", controllers.UserList)
	rpc.Method("user.get", controllers.UserGet)
	rpc.Method("user.get", controllers.UserGet)
	rpc.Method("target.addon_create", controllers.TargetAddonCreate)
	rpc.Method("target.addon_delete", controllers.TargetAddonDelete)
	rpc.Method("target.addon_reset", controllers.TargetAddonReset)
	rpc.Method("target.delete", controllers.TargetDelete)
	rpc.Method("target.get", controllers.TargetGet)
	rpc.Method("target.list", controllers.TargetList)
	rpc.Method("target.relation_create", controllers.TargetRelationCreate)
	rpc.Method("target.relation_delete", controllers.TargetRelationDelete)
	rpc.Method("target.upsert", controllers.TargetUpsert)
	rpc.Method("target.user_delete", controllers.TargetUserDelete)
	rpc.Method("target.user_upsert", controllers.TargetUserUpsert)
